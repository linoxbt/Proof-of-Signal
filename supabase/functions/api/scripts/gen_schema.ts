// Generates lib/validate_payload.generated.js: an Ajv standalone validator for
// schema/test-payload.schema.json, so the function never compiles code at
// runtime (no `new Function`). Run `deno task gen-schema` after changing the
// schema; tests/unit_checks_schema.test.ts fails while the file is stale.

import Ajv2020 from "npm:ajv@8.17.1/dist/2020.js";
import standaloneCode from "npm:ajv@8.17.1/dist/standalone/index.js";
import addFormats from "npm:ajv-formats@3.0.1";

const SCHEMA = new URL("../schema/test-payload.schema.json", import.meta.url);
export const OUTPUT = new URL("../lib/validate_payload.generated.js", import.meta.url);

// Runtime helpers the generated code requires, pinned to the same versions.
const PACKAGES: Record<string, string> = { "ajv": "npm:ajv@8.17.1", "ajv-formats": "npm:ajv-formats@3.0.1" };

export async function generate(): Promise<string> {
  const schema = JSON.parse(await Deno.readTextFile(SCHEMA));
  // deno-lint-ignore no-explicit-any
  const ajv = new (Ajv2020 as any)({ strict: true, allowUnionTypes: true, code: { source: true, esm: true } });
  // deno-lint-ignore no-explicit-any
  (addFormats as any)(ajv, ["uuid", "date-time"]);
  // deno-lint-ignore no-explicit-any
  let code: string = (standaloneCode as any)(ajv, ajv.compile(schema));

  // Ajv's ESM output still uses require() for runtime helpers: hoist them to imports.
  const imports: string[] = [];
  const seen = new Map<string, string>();
  code = code.replace(/require\("([^"]+)"\)/g, (_m, spec: string) => {
    if (!seen.has(spec)) {
      const pkg = Object.keys(PACKAGES).find((p) => spec.startsWith(p + "/"));
      if (!pkg) throw new Error(`unexpected require(${spec})`);
      const id = `__dep${seen.size}`;
      seen.set(spec, id);
      imports.push(`import ${id} from "${PACKAGES[pkg]}${spec.slice(pkg.length)}.js";`);
    }
    return seen.get(spec)!;
  });
  return [
    '// @ts-self-types="./validate_payload.generated.d.ts"',
    "// deno-lint-ignore-file",
    "// GENERATED by scripts/gen_schema.ts from schema/test-payload.schema.json. Do not edit.",
    ...imports,
    code,
    "",
  ].join("\n");
}

if (import.meta.main) {
  await Deno.writeTextFile(OUTPUT, await generate());
  console.log(`wrote ${OUTPUT.pathname}`);
}
